# Definition for a binary tree node.
# class TreeNode(object):
#     def __init__(self, val=0, left=None, right=None):
#         self.val = val
#         self.left = left
#         self.right = right
class Solution(object):
    def searchBST(self, root, val):
        
        while root:
            if val < root.val:
             
                root = root.left
            elif val > root.val:
                
                root = root.right
            elif val == root.val:
                return root
        return 
            


        

